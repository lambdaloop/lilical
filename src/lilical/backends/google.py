def _load_client_config() -> dict[str, object]:
    # 1. Env vars — always win; useful for contributors and CI.
    client_id = os.environ.get("LILICAL_GOOGLE_CLIENT_ID")
    client_secret = os.environ.get("LILICAL_GOOGLE_CLIENT_SECRET")
    if client_id and client_secret:
        return {
            "installed": {
                "client_id": client_id,
                "client_secret": client_secret,
                "redirect_uris": ["http://127.0.0.1"],
                "auth_uri": os.environ.get(
                    "LILICAL_GOOGLE_AUTH_URI",
                    "https://accounts.google.com/o/oauth2/auth",
                ),
                "token_uri": os.environ.get(
                    "LILICAL_GOOGLE_TOKEN_URI",
                    "https://oauth2.googleapis.com/token",
                ),
            }
        }

    # 2. Embedded module — generated by tools/generate_oauth_embedded.py at
    #    build time and frozen into Flatpak/AppImage bundles.
    try:
        from lilical import _oauth_embedded  # type: ignore[import]

        return {
            "installed": {
                "client_id": _oauth_embedded.CLIENT_ID,
                "client_secret": _oauth_embedded.CLIENT_SECRET,
                "redirect_uris": ["http://127.0.0.1"],
                "auth_uri": _oauth_embedded.AUTH_URI,
                "token_uri": _oauth_embedded.TOKEN_URI,
            }
        }
    except ImportError:
        pass

    # 3. oauth_credentials.json at the repo root — picked up in dev when
    #    running via `pixi run run` without env vars set.
    for parent in Path(__file__).resolve().parents:
        candidate = parent / "oauth_credentials.json"
        if candidate.is_file():
            with candidate.open() as f:
                data: dict[str, object] = json.load(f)
            installed = dict(cast(dict[str, object], data.get("installed", {})))
            installed.setdefault("redirect_uris", ["http://127.0.0.1"])
            return {"installed": installed}

    # 4. Placeholder — _validate_client_config will raise a clear error.
    return {"installed": {"client_id": "lilical-oauth", "client_secret": ""}}


